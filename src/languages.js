'use strict';

/**
 * Единственное место, где инструмент "знает" про языки программирования:
 * как в файле с данным расширением выглядят комментарии.
 *
 *   block: [[открытие, закрытие], ...]  — блочные комментарии
 *   line:  [префикс, ...]               — строчные комментарии (подряд идущие строки склеиваются)
 *
 * Комментарий попадает в документацию, только если внутри есть тег @api...
 * Поэтому "лишние" комментарии безопасны.
 *
 * Чтобы добавить язык, достаточно одной строки здесь
 * или записи "languages" в apiscribe.config.json.
 */

const C_LIKE = { block: [['/**', '*/']], line: ['//'] };

module.exports = {
  '.js': C_LIKE,
  '.mjs': C_LIKE,
  '.cjs': C_LIKE,
  '.jsx': C_LIKE,
  '.ts': C_LIKE,
  '.tsx': C_LIKE,
  '.java': C_LIKE,
  '.kt': C_LIKE,
  '.scala': C_LIKE,
  '.groovy': C_LIKE,
  '.go': C_LIKE,
  '.cs': C_LIKE,
  '.c': C_LIKE,
  '.cpp': C_LIKE,
  '.h': C_LIKE,
  '.swift': C_LIKE,
  '.dart': C_LIKE,
  '.php': { block: [['/**', '*/']], line: ['//', '#'] },
  '.rs': { block: [['/**', '*/']], line: ['///', '//'] },
  '.py': { block: [['"""', '"""'], ["'''", "'''"]], line: ['#'] },
  '.rb': { line: ['#'] },
  '.sh': { line: ['#'] },
  '.lua': { line: ['--'] },
};
